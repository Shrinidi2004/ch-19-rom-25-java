class Clothes {

	static String clothType;
	static String color;
	static int size;
	static double price;
	static boolean isUnisex;
	static String brand;

	public static String getclothType(){
		clothType = "T-Shirt";
		return clothType;
	}
	public static String getcolor(){
		color = "Blue";
		return color;
	}
	public static int getsize(){
		size = 42;
		return size;
	}
	public static double getprice(){
		price = 799.99;
		return price;
	}
	public static boolean getisUnisex(){
		isUnisex = true;
		return isUnisex;
	}
	public static String getbrand(){
		brand = "Levi's";
		return brand;
	}
}

