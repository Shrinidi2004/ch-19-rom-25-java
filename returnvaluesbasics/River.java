class River {

	static String riverName;
	static double lengthKm;
	static int numberOfBridges;
	static boolean isPolluted;
	static String originState;
	static String endPoint;

	public static String getriverName(){
		riverName = "Godavari";
		return riverName;
	}
	public static double getlengthKm(){
		lengthKm = 1465.0;
		return lengthKm;
	}
	public static int getnumberOfBridges(){
		numberOfBridges = 9;
		return numberOfBridges;
	}
	public static boolean getisPolluted(){
		isPolluted = false;
		return isPolluted;
	}
	public static String getoriginState(){
		originState = "Maharashtra";
		return originState;
	}
	public static String getendPoint(){
		endPoint = "Bay of Bengal";
		return endPoint;
	}
}

